// Builds temporary diagnostic backdrops to find what freezes the scene in the desktop app.
// usage: node scene/build-probes.mjs scene/erid-dome.svg <out probes.ts>
// Not part of the shipped mod: wire PROBES into a temporary `/…-probe` command (see docs/troubleshooting.md).
import fs from 'node:fs'

const full = fs.readFileSync(process.argv[2], 'utf8')
const css = full.match(/<style>([\s\S]*?)<\/style>/)[1]
const mediaAt = css.indexOf('@media (prefers-color-scheme')
const media = css.slice(mediaAt)
const imp = 'rect{stroke:none!important}path{fill:none!important}'
const rest = css.slice(0, mediaAt).replace(imp, '')
const palette = (rest.match(/\.c\d+\{[^}]*\}/g) || []).join('')
const anim = rest.replace(/\.c\d+\{[^}]*\}/g, '')

// big, unmistakable motion: an orange disc crossing the screen, a bar blinking
const BIG_CSS = '.bgA{animation:bgA 4s linear infinite alternate}@keyframes bgA{to{transform:translateX(1000px)}}.bgB{animation:bgB 1s linear infinite alternate}@keyframes bgB{to{opacity:.1}}'
const BIG = '<circle class="bgA" cx="300" cy="450" r="200" fill="#e0562b"/><rect class="bgB" x="0" y="820" width="1600" height="60" fill="#1d6fd6"/>'
const shell = (style, inner) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" preserveAspectRatio="xMinYMid slice"><style>${style}</style><rect width="1600" height="900" fill="#dfe3e1"/>${inner}</svg>`

const withBig = svg => svg.replace('</style>', BIG_CSS + '</style>').replace(/<\/svg>$/, BIG + '</svg>')

const PROBES = {
  big: shell(BIG_CSS, BIG), //                         my hook path, plain motion
  'big-css': shell(BIG_CSS + css, BIG), //              + the scene's whole stylesheet
  'big-media': shell(BIG_CSS + media, BIG), //          + only the dark-mode @media block
  'big-imp': shell(BIG_CSS + imp, BIG), //              + only the two !important rules
  'big-anim': shell(BIG_CSS + anim, BIG), //            + only the scene's animation rules
  'big-markup': full.replace('</style>', BIG_CSS + '</style>').replace(/<\/svg>$/, BIG + '</svg>'), // whole scene + big motion
  // size alone: plain disc + an invisible 115k-character path
  'big-size': shell(BIG_CSS, BIG + `<path opacity="0" d="${'M0 0h1'.repeat(19000)}"/>`),
  // the scene's markup minus the dithered <pattern> fills
  'big-nopat': full.replace(/<pattern[\s\S]*?<\/pattern>/g, '').replace(/<rect fill="url\(#[db]\d\)"[^>]*\/>/g, '').replace('</style>', BIG_CSS + '</style>').replace(/<\/svg>$/, BIG + '</svg>'),
  // the scene with its biggest paths (the rock raster) halved: smaller source, same CSS and features
  'big-half': (() => { let n = 0; return full.replace(/<path class="c\d+" d="([^"]{3000,})"\/>/g, (m, d) => (n++ % 2 ? '' : m)) })().replace('</style>', BIG_CSS + '</style>').replace(/<\/svg>$/, BIG + '</svg>'),
  // structural features, one removed per probe (the whole scene otherwise, plus the disc)
  'm-noclip': withBig(full.replace(/<clipPath[\s\S]*?<\/clipPath>/g, '').replace(/ clip-path="[^"]*"/g, '')),
  'm-nocrisp': withBig(full.replace(/ shape-rendering="crispEdges"/g, '')),
  'm-noscale': withBig(full.replace(/ transform="scale\([^)]*\)"/g, '')),
  'm-tiny': withBig(full.replace(/<path class="c\d+" d="[^"]{600,}"\/>/g, '')),
}
for (const [k, v] of Object.entries(PROBES)) console.log(k.padEnd(11), v.length)
fs.writeFileSync(process.argv[3], `// Generated by scene/build-probes.mjs — temporary diagnostics.\nexport const PROBES: Record<string, string> = ${JSON.stringify(PROBES)}\n`)
